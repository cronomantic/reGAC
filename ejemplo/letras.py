def bytes_of(rows):
    out = bytearray()
    for row in rows:
        value = 0
        for bit, cell in enumerate(row):
            if cell == "#":
                value |= 0x80 >> bit
        out.append(value)
    return bytes(out)


def dump():
    out = bytearray()
    # ninety six from the space, and the last of them is where these machines
    # keep the copyright sign rather than the delete they have no use for
    for code in range(32, 128):
        char = "©" if code == 127 else chr(code)
        rows = ART.get(char)
        assert rows is not None, f"no glyph for {char!r} ({code})"
        out += bytes_of(rows)
    assert len(out) == 768, len(out)
    return bytes(out)


